#!/usr/bin/env python3
"""UART RX 8N1 firmware for the engine; writes src/fpga/uart_rx_prog.hex."""
import argparse
import os

from fw_layout import org, place
from uart_workload import F_CLK, ROOT, word

IN_PIN = 1


def uart_rx_program(D):
    """Bit period = D+2 cycles (IN1 D + DJNZ). The first IN1 samples W+3..W+4 cycles
    after the start edge (2-flop sync, WAITL exit, SETL), so W centres it on data bit 0."""
    cpb = D + 2
    W = round(1.5 * cpb) - 4
    return [
        (word("CFG", IN_PIN << 3), f"CFG   {IN_PIN << 3:<6} out_pin=0, in_pin={IN_PIN}, LSB first"),
        (word("WAITH", IN_PIN),    f"WAITH {IN_PIN:<6} line idle first (pin_block syncs reset to 0 = fake start bit)"),
        (word("WAITL", IN_PIN),    f"WAITL {IN_PIN:<6} block until start bit (line low)"),
        (word("SETL", 8),          "SETL  8      8 data bits"),
        (word("WAIT", W),          f"WAIT  {W:<6} to middle of data bit 0"),
        (word("IN1", D),           f"IN1   {D:<6} sample data bit (LSB first)"),
        (word("DJNZ", 5),          "DJNZ  5"),
        (word("PUSH"),             "PUSH         ISR -> rx_fifo (byte in [31:24]), clear ISR"),
        (word("JMP", 1),           "JMP   1      next byte"),
    ]


def write_hex(path, D, baud):
    prog = uart_rx_program(D)
    halt = word("HALT")
    if org():                                 # FW_ORG: write the relocated 256-word image
        img = place([w for w, _ in prog])
        with open(path, "w", newline="\n") as f:
            f.write(f"// Generated by host/uart_rx_prog.py FW_ORG={org()} -- do not edit.\n@00\n")
            f.write("".join(f"{w:08X}\n" for w in img))
        return
    with open(path, "w", newline="\n") as f:
        f.write(f"// Generated by host/uart_rx_prog.py -- do not edit.\n")
        f.write(f"// UART RX 8N1, LSB first, in_pin={IN_PIN}. Bit period = D+2 cycles; "
                f"D={D} -> {D + 2} cycles = {baud} baud @ {F_CLK // 1_000_000} MHz.\n")
        f.write("// No stop-bit / framing check. Word = {opcode[4:0], operand[26:0]}.\n")
        f.write("@00\n")
        for i, (w, c) in enumerate(prog):
            f.write(f"{w:08X} // {i:02d} {c}\n")
        f.write(f"@{len(prog):02X}\n")
        fill = [f"{halt:08X}"] * (64 - len(prog))
        for i in range(0, len(fill), 8):
            f.write(" ".join(fill[i:i + 8]) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baud", type=int, default=115200)
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "fpga", "uart_rx_prog.hex"))
    args = ap.parse_args()
    D = round(F_CLK / args.baud) - 2
    write_hex(args.out, D, args.baud)
    print(f"wrote {args.out} (baud={args.baud}, D={D})")


if __name__ == "__main__":
    main()
