#!/usr/bin/env python3
"""CAN 2.0A on the engine (host/can_prog.py), against
  - a Verilog bus node (tb/peer_can.v) that acknowledges good frames and prints what it received,
  - a Python bit-level decoder of the pad waveform (host/can_model.py) that checks every wire bit, the bit grid, the ACK slot and EOF/IFS,
  - waveforms generated by the Python encoder (good frames, bad CRC, stuff errors, form errors, RTR / extended frames, clock error),
  - engine 0 sending to engine 1 over the same bus.
  python host/can_test.py [run mutants]
"""
import random
import re
import sys
from bisect import bisect_right

import can_model as cm
import can_prog as cp
import proto_lib as pl

EV = cp.EV
RESULTS = []
B_CLK = 100                          # clocks per bit (500 kbit/s)
GRID_TOL_NS = 2 * pl.NS_PER_CLK      # every edge of the transmitter lies within 2 clocks of the bit grid
ACK_TOL_NS = 3 * pl.NS_PER_CLK       # the receiver's ACK slot edges lie within 3 clocks of the slot boundaries


def report(name, errs, stats, expect="pass"):
    ok = bool(errs) == (expect == "fail")
    tag = {"pass": "PASS" if ok else "FAIL", "fail": "DETECTED" if ok else "MISSED"}[expect]
    RESULTS.append((name, ok))
    print(f"  {tag:8s} {name:62s} {stats}")
    if not ok:
        for e in errs[:6] or ["no error was reported"]:
            print(f"           {e}")
    return ok


def pack_words(data):
    ws = []
    for i in range(0, len(data), 4):
        c = list(data[i:i + 4]) + [0] * 4
        ws.append(c[0] << 24 | c[1] << 16 | c[2] << 8 | c[3])
    return ws


def stuff_positions(bits):
    """Indices (in the unstuffed list) after which a stuff bit is inserted."""
    pos, run, last = [], 0, None
    for i, b in enumerate(bits):
        if b == last:
            run += 1
        else:
            run, last = 1, b
        if run == 5:
            pos.append(i)
            last, run = 1 - b, 1
    return pos


# ---------------------------------------------------------------- pad decoding
def bus_frames(tl, bit_ns, tol_ns=GRID_TOL_NS, horizon=None, ack_tol_ns=None):
    """Every frame found on the bus: [dict(t_sof, bits (SOF .. end of EOF), dec, edge_errs)]. A frame ends 10 bits after its CRC sequence."""
    times = [t for t, _ in tl]

    def level(t):
        i = bisect_right(times, t) - 1
        return tl[i][1] if i >= 0 else 1
    out, cursor = [], 0.0
    t_last = horizon if horizon is not None else tl[-1][0]
    while True:
        t_sof = next((t for t, l in tl if l == 0 and t >= cursor), None)
        if t_sof is None:
            break
        bits = [level(t_sof + (k + 0.5) * bit_ns) for k in range(220)]
        dec = cm.decode_wire(bits)
        n = dec.get("n_wire", 20) + 10
        fb = bits[:n]
        edge_errs = []
        for t, _ in tl[1:]:
            if t_sof <= t < t_sof + n * bit_ns:
                r = (t - t_sof) / bit_ns
                nw = dec.get("n_wire", -9)
                tol = ack_tol_ns if ack_tol_ns and (abs(r - (nw + 1)) < 0.5 or abs(r - (nw + 2)) < 0.5) else tol_ns   # ACK slot edges come from the receiver
                if abs(r - round(r)) * bit_ns > tol:
                    edge_errs.append(f"edge at {t} ns is {abs(r - round(r)) * bit_ns:.0f} ns off the bit grid (frame at {t_sof} ns)")
        out.append(dict(t_sof=t_sof, bits=fb, dec=dec, edge_errs=edge_errs, n=n))
        cursor = t_sof + n * bit_ns
        if cursor > t_last:
            break
    return out


def peer_lines(L):
    return [ln for ln in L["STDOUT"] if ln.startswith("CANRX") or ln.startswith("CANERR")]


def parse_canrx(ln):
    m = re.match(r"CANRX t=(\d+) id=(\d+) dlc=(\d+) rtr=(\d) data=([0-9a-fA-Fx]+) crc=(\d) ack=(\d)", ln)
    t, i, dlc, rtr, data, crc, ack = m.groups()
    nb = min(int(dlc), 8)
    d = int(data, 16).to_bytes(8, "big")[8 - nb:] if nb else b""
    return dict(t=int(t), id=int(i), dlc=int(dlc), rtr=int(rtr), data=list(d), crc=int(crc), ack=int(ack))


# ---------------------------------------------------------------- engine as transmitter
def tx_case(name, frames, cpb=B_CLK, ack=True, firmware=None, expect="pass", peer=3, label=None):
    """frames: [(id, data)] or [(id, data, dlc)]. Engine 0 transmits all of them; the bus node acknowledges (or not)."""
    bit_ns = cpb * pl.NS_PER_CLK
    words, enc = [], []
    for fr in frames:
        ident, data = fr[0], fr[1]
        dlc = fr[2] if len(fr) > 2 else len(data)
        words += cp.host_words(ident, data, dlc)
        enc.append(cm.encode(ident, data, dlc=dlc))
    dur = len(frames) * (150 + 20) * bit_ns + 40 * bit_ns + 10_000
    L = pl.run(name, progs={0: firmware or cp.can_tx(cpb)}, htx={0: words}, od=0x01, peer=peer, dur_ns=dur,
               plus={"CAN_BIT_NS": bit_ns, "CAN_ACK": 1 if ack else 0})
    errs = []
    got = [w for _, w in L["A"]]
    exp = [EV | (1 if ack else 0)] * len(frames)
    if got != exp:
        errs.append(f"RX words {[hex(w) for w in got]} vs {[hex(w) for w in exp]}")
    fr_bus = bus_frames(pl.timeline(L["P"], 0), bit_ns, horizon=dur - 20 * bit_ns)
    if len(fr_bus) != len(frames):
        errs.append(f"{len(fr_bus)} frames on the bus, expected {len(frames)}")
    prev_end = None
    for k, (f, b) in enumerate(zip(enc, fr_bus)):
        want = f.wire(ack=0 if ack else 1, ifs=0)
        if b["bits"] != want:
            j = next((i for i, (x, y) in enumerate(zip(b["bits"], want)) if x != y), min(len(b["bits"]), len(want)))
            errs.append(f"frame {k} (id {f.ident:#x}): wire bit {j} differs ({b['bits'][j] if j < len(b['bits']) else '-'} vs "
                        f"{want[j] if j < len(want) else '-'}), lengths {len(b['bits'])}/{len(want)}")
        errs += [f"frame {k}: {e}" for e in b["edge_errs"][:2]]
        if b["dec"].get("errors"):
            errs.append(f"frame {k}: decoder: {b['dec']['errors']}")
        if prev_end is not None and b["t_sof"] - prev_end < 3 * bit_ns - GRID_TOL_NS:
            errs.append(f"frame {k}: intermission {(b['t_sof'] - prev_end) / bit_ns:.2f} bit times < 3")
        prev_end = b["t_sof"] + b["n"] * bit_ns
    if peer == 3:
        pl_ = [parse_canrx(ln) for ln in peer_lines(L) if ln.startswith("CANRX")]
        if len(pl_) != len(frames):
            errs.append(f"bus node saw {len(pl_)} frames, expected {len(frames)}")
        for k, (f, p) in enumerate(zip(enc, pl_)):
            n = min(f.dlc, 8)
            if (p["id"], p["dlc"], p["data"], p["crc"], p["ack"]) != (f.ident, f.dlc, f.data[:n], 1, 1 if ack else 0):
                errs.append(f"bus node frame {k}: {p} vs id {f.ident:#x} dlc {f.dlc} data {f.data[:n]}")
        if any(ln.startswith("CANERR") for ln in peer_lines(L)):
            errs.append("bus node reported an error: " + [ln for ln in peer_lines(L) if ln.startswith("CANERR")][0])
    if L["END"].get("fault0", 0) or L["END"].get("contend", 0):
        errs.append(f"END {L['END']}")
    return report(name, errs, f"{len(frames)} frames, {sum(len(x['bits']) for x in fr_bus)} wire bits", expect)


def find_frames(rnd):
    """Frames that put stuff bits at the section boundaries and behind the CRC (the places the firmware has special cases for)."""
    want = {"hdr_end": None, "word_end": None, "data_end": None, "crc_end": None}
    for _ in range(200000):
        n = rnd.choice((0, 8))                    # DLC 0 is the only way to get five equal bits ending the header
        f = cm.encode(rnd.randrange(0x800), [rnd.choice((0, 255, rnd.randrange(256))) for _ in range(n)])
        pre = f.pre_crc()
        full = pre + cm.to_bits(cm.crc15(pre), 15)
        pos = set(stuff_positions(full))
        if want["hdr_end"] is None and 18 in pos:
            want["hdr_end"] = f
        if want["word_end"] is None and 19 + 31 in pos:
            want["word_end"] = f
        if want["data_end"] is None and len(pre) - 1 in pos:
            want["data_end"] = f
        if want["crc_end"] is None and len(full) - 1 in pos:
            want["crc_end"] = f
        if all(want.values()):
            break
    assert all(want.values()), want
    return [(f.ident, f.data) for f in want.values()]


def phase_tx():
    print("Phase 1: engine transmits, bus node + Python decoder check the wire")
    rnd = random.Random(61)
    tx_case("every DLC 0..8, random ID and data", [(rnd.randrange(0x800), [rnd.randrange(256) for _ in range(d)]) for d in range(9)])
    tx_case("worst-case stuffing: all-dominant and all-recessive frames",
            [(0x000, [0] * 8), (0x7FF, [0xFF] * 8), (0x000, []), (0x7FF, [])])
    tx_case("alternating patterns (no stuffing at all)", [(0x555, [0x55] * 4), (0x2AA, [0xAA] * 8), (0x155, [0x55, 0xAA, 0x55])])
    tx_case("stuff bits at header end, word end, data end, behind the CRC", find_frames(rnd))
    tx_case("DLC 9..15 means 8 data bytes", [(0x321, [rnd.randrange(256) for _ in range(8)], d) for d in (9, 12, 15)])
    tx_case("identifier walking ones / zeros", [(1 << k, [k]) for k in range(11)] + [(0x7FF ^ (1 << k), [k, 0xFF]) for k in range(11)])
    tx_case("40 random frames back to back",
            [(rnd.randrange(0x800), [rnd.randrange(256) for _ in range(rnd.randrange(9))]) for _ in range(40)])
    tx_case("no node acknowledges: the ACK slot stays recessive", [(0x100, [1, 2, 3]), (0x101, [])], ack=False)
    for cpb in (50, 250):
        tx_case(f"bit time {cpb} clocks ({50e6 / cpb / 1000:.0f} kbit/s)", [(0x2C3, [0x12, 0x34, 0x56]), (0x7FF, [0xFF] * 8)], cpb=cpb)
    # engine 0 -> engine 1 over the same bus (no Verilog node)
    if pl.CHIP:
        print("  (skipped on the chip: the receiver would have to drive the ACK slot on a pad that engine 0 owns - one owner per pad)")
        return
    frames = [(rnd.randrange(0x800), [rnd.randrange(256) for _ in range(d)]) for d in (0, 1, 4, 8, 3)] + find_frames(rnd)[:2]
    words = [w for fr in frames for w in cp.host_words(*fr)]
    bit_ns = B_CLK * pl.NS_PER_CLK
    dur = len(frames) * 170 * bit_ns + 100_000
    L = pl.run("can_e0_to_e1", progs={0: cp.can_tx(B_CLK), 1: cp.can_rx(B_CLK)}, htx={0: words}, od=0x01, dur_ns=dur)
    errs = []
    if [w for _, w in L["A"]] != [EV | 1] * len(frames):
        errs.append(f"sender events {[hex(w) for _, w in L['A']]}")
    exp = []
    for ident, data in frames:
        exp += rx_expect(cm.encode(ident, data))
    got = [w for _, w in L["B"]]
    if got != exp:
        k = next((i for i, (g, e) in enumerate(zip(got, exp)) if g != e), min(len(got), len(exp)))
        errs.append(f"receiver words: {len(got)} vs {len(exp)}, first difference at #{k}: "
                    f"{got[k] if k < len(got) else '-'} vs {exp[k] if k < len(exp) else '-'}")
    fb = bus_frames(pl.timeline(L["P"], 0), bit_ns, horizon=dur - 20 * bit_ns, ack_tol_ns=ACK_TOL_NS)
    errs += [e for b in fb for e in b["edge_errs"][:2]]
    if L["END"].get("fault0", 0) or L["END"].get("fault1", 0) or L["END"].get("contend", 0):
        errs.append(f"END {L['END']}")
    report("engine 0 sends, engine 1 receives and acknowledges", errs, f"{len(frames)} frames")


# ---------------------------------------------------------------- engine as receiver
def rx_expect(f, err=0, q=None):
    """Words the receiver pushes for Frame f. err = status code; q = number of unstuffed bits received before a stuff error."""
    n = min(f.dlc, 8)
    nbits = 19 + 8 * n
    if err == 4:
        return [EV | 1 << 25 | 4 << 4]
    if err == 1:
        ws = []
        if q is not None and q >= 19:
            ws.append(EV | f.dlc << 12 | f.ident)
            data = pack_words(f.data[:n])
            done = len(data) if q >= nbits else min((q - 19) // 32, len(data))
            ws += data[:done]
        return ws + [EV | 1 << 25 | 1 << 4]
    ws = [EV | f.dlc << 12 | f.ident] + pack_words(f.data[:n])
    ws.append(EV | 1 << 25 | err << 4 | (1 if err == 0 else 0))
    return ws


def corrupt_crc(f, bit):
    pre = f.pre_crc()
    c = cm.crc15(pre) ^ (1 << bit)
    return cm.stuff(pre + cm.to_bits(c, 15)) + [1, 1, 1] + [1] * 7 + [1] * 3


def stuff_violation(f, which=0):
    """Wire bits of frame f with the `which`-th stuff bit replaced by a copy of the previous bit (six equal bits). Returns (bits, q)
    where q is the number of unstuffed bits before the violation."""
    w = f.wire(ack=1)
    full = f.pre_crc() + cm.to_bits(cm.crc15(f.pre_crc()), 15)
    pos = stuff_positions(full)
    p = pos[which]
    wi = p + 1 + which                       # wire index of the stuff bit (p unstuffed bits + `which` earlier stuff bits + the bit itself)
    assert w[wi] != w[wi - 1]
    bits = list(w)
    bits[wi] = bits[wi - 1]
    return bits, p + 1


def rx_case(name, items, cpb=B_CLK, scale=1.0, firmware=None, expect="pass", words_only=False):
    """items: [(wire_bits, expected_words, acked, ack_index)] - the waveform is the wire bits back to back (3 recessive bits of
    intermission are part of the lists); the engine must push the expected words and, for acked frames, pull the ACK slot low."""
    bit_ns = cpb * pl.NS_PER_CLK
    wires = [it[0] for it in items]
    ev, end, starts = cm.merge_frames(wires, bit_ns, start_ns=3000, scale=scale)
    dur = end + 40 * bit_ns - 3000 + 3000
    L = pl.run(name, progs={0: firmware or cp.can_rx(cpb)}, od=0x01, stim=ev, dur_ns=dur, plus={"WAND": "01"})
    errs = []
    exp = [w for it in items for w in it[1]]
    got = [w for _, w in L["A"]]
    if got != exp:
        k = next((i for i, (g, e) in enumerate(zip(got, exp)) if g != e), min(len(got), len(exp)))
        errs.append(f"RX words: {len(got)} vs {len(exp)}, first difference at #{k}: "
                    f"{got[k]:#x} vs {exp[k]:#x}" if k < min(len(got), len(exp)) else f"RX words: {len(got)} vs {len(exp)}")
    # the pad is the wired AND of the waveform and the engine: rebuild the expected pad waveform
    tl = pl.timeline(L["P"], 0)
    times = [t for t, _ in tl]

    def level(t):
        i = bisect_right(times, t) - 1
        return tl[i][1] if i >= 0 else 1
    worst = 0.0
    for k, (it, t0) in enumerate(zip(items, starts)):
        bits, _, acked, ack_idx = it
        bn = bit_ns * scale
        if words_only:
            continue
        for j, b in enumerate(bits):
            want = 0 if (acked and j == ack_idx) else b
            got_l = level(t0 + (j + 0.5) * bn)
            if got_l != want:
                errs.append(f"frame {k}: pad bit {j} is {got_l}, expected {want} ({'ACK slot' if j == ack_idx else 'frame'})")
                break
        if acked:
            e = [t for t, l in tl if l == 0 and abs(t - (t0 + ack_idx * bn)) < 0.4 * bn]
            r = [t for t, l in tl if l == 1 and abs(t - (t0 + (ack_idx + 1) * bn)) < 0.4 * bn]
            nxt_dominant = bits[ack_idx + 1] == 0 if ack_idx + 1 < len(bits) else False
            if not e or (not r and not nxt_dominant):
                errs.append(f"frame {k}: no ACK edges found")
                continue
            d0 = e[0] - (t0 + ack_idx * bn)
            d1 = (r[0] - (t0 + (ack_idx + 1) * bn)) if r else d0
            worst = max(worst, abs(d0), abs(d1))
            if scale == 1.0:
                if abs(d0) > ACK_TOL_NS or abs(d1) > ACK_TOL_NS:
                    errs.append(f"frame {k}: ACK slot edges {d0:.0f} / {d1:.0f} ns from the slot boundaries")
            else:
                # clock error: the dominant pulse must cover the sender's sample point (75 %) and end before the next one
                lo, hi = t0 + (ack_idx + 0.75) * bn, t0 + (ack_idx + 1.75) * bn
                if not (e[0] <= lo and (not r or lo <= r[0] <= hi)):
                    errs.append(f"frame {k}: ACK pulse {e[0] - t0:.0f}..{(r[0] - t0) if r else 0:.0f} ns misses the sender's sample point")
    if L["END"].get("fault0", 0) or L["END"].get("contend", 0):
        errs.append(f"END {L['END']}")
    return report(name, errs, f"{len(items)} frames, {len(exp)} words" + (f", ACK edges within {worst:.0f} ns" if worst else ""), expect)


def good(f):
    return (f.wire(ack=1), rx_expect(f), True, f.stuffed_len() + 1)


def phase_rx():
    print("Phase 2: engine receives frames from a Python waveform")
    rnd = random.Random(62)
    rf = lambda d=None: cm.random_frame(rnd, d)
    rx_case("good frames, every DLC 0..8", [good(rf(d)) for d in range(9)])
    ff = [cm.encode(i, d) for i, d in find_frames(rnd)]
    rx_case("stuff bits at header end, word end, data end, behind the CRC", [good(f) for f in ff])
    rx_case("all-dominant / all-recessive frames", [good(cm.encode(0, [0] * 8)), good(cm.encode(0x7FF, [0xFF] * 8)),
                                                    good(cm.encode(0, [])), good(cm.encode(0x7FF, []))])
    rx_case("DLC 9..15 means 8 data bytes", [good(cm.encode(0x1AB, [rnd.randrange(256) for _ in range(8)], dlc=d)) for d in (9, 15)])
    rx_case("30 random frames at the minimum intermission", [good(rf()) for _ in range(30)])
    # bad frames
    f = rf(5)
    items = []
    for bit in (0, 7, 14):
        items.append((corrupt_crc(f, bit), rx_expect(f, 2), False, 0))
    items.append(good(rf(3)))
    rx_case("a flipped CRC bit is detected, not acknowledged, and the next frame is fine", items)
    f = cm.encode(0x234, [rnd.randrange(256) for _ in range(8)])
    items = []
    for w in (0, 1, 3):
        bits, q = stuff_violation(f, w)
        items.append((bits + [1] * 20, rx_expect(f, 1, q), False, 0))
    items.append(good(rf(2)))
    rx_case("stuff error (six equal bits) at header, data and later positions", items)
    fs = [cm.encode(0x000, [0] * 8), cm.encode(0x7FF, [0xFF] * 8)]
    items = []
    for f in fs:
        for w in (0, 5, 12, 20):
            full = f.pre_crc() + cm.to_bits(cm.crc15(f.pre_crc()), 15)
            if w < len(stuff_positions(full)):
                bits, q = stuff_violation(f, w)
                items.append((bits + [1] * 20, rx_expect(f, 1, q), False, 0))
    items.append(good(rf(1)))
    rx_case("stuff errors in the middle of long runs, in every data word", items)
    # unsupported frames: remote request and extended frame
    fr = cm.encode(0x155, [], rtr=1, dlc=3)
    ext = cm.encode(0x0AA, [1, 2], dlc=2)
    wr = cm.stuff(fr.pre_crc() + cm.to_bits(cm.crc15(fr.pre_crc()), 15)) + [1, 1, 1] + [1] * 10
    pre = ext.pre_crc()
    pre[13] = 1                                                  # IDE = 1: an extended frame - the receiver does not follow it
    we = cm.stuff(pre + cm.to_bits(cm.crc15(pre), 15)) + [1, 1, 1] + [1] * 10
    rx_case("remote and extended frames are reported as unsupported, the bus recovers",
            [(wr, rx_expect(fr, 4), False, 0), (we, rx_expect(ext, 4), False, 0), good(rf(4))])
    # form errors
    f = rf(4)
    wdel = f.wire(ack=1)
    k = f.stuffed_len()
    bad_delim = list(wdel); bad_delim[k] = 0
    bad_eof = list(wdel); bad_eof[k + 5] = 0
    bad_adel = list(wdel); bad_adel[k + 2] = 0
    rx_case("form errors: dominant CRC delimiter / ACK delimiter / EOF bit",
            [(bad_delim, rx_expect(f, 3), False, k + 1), (bad_adel, rx_expect(f, 3), True, k + 1),
             (bad_eof, rx_expect(f, 3), True, k + 1), good(rf(2))])
    # clock tolerance of the receiver
    long_frames = [good(rf()) for _ in range(4)] + [good(cm.encode(0, [0] * 8))]
    for pct in (-0.15, 0.15):
        rx_case(f"sender clock error {pct:+.2f} % (data and ACK slot)", long_frames, scale=1 + pct / 100)
    for pct in (-0.3, 0.3):
        rx_case(f"sender clock error {pct:+.2f} % (data only)", long_frames, scale=1 + pct / 100, words_only=True)
    for cpb in (50, 250):
        rx_case(f"bit time {cpb} clocks", [good(rf(d)) for d in (0, 3, 8)] + [good(cm.encode(0x7FF, [0xFF] * 8))], cpb=cpb)


def phase_mutants():
    print("Phase 3: broken firmware must be caught")
    rnd = random.Random(63)
    # ---- transmitter
    tx_frames = [(rnd.randrange(0x800), [rnd.randrange(256) for _ in range(d)]) for d in (0, 2, 5, 8)] + find_frames(rnd) + \
        [(0x000, [0] * 8), (0x7FF, [0xFF] * 8), (0x321, [1] * 8, 12)]
    for name, kw in (("stuffing after 4 equal bits", dict(mut=("stuff4",))),
                     ("stuff bits are fed to the CRC", dict(mut=("feed_stuff",))),
                     ("no stuff bit behind the last CRC bit", dict(mut=("no_end_stuff",))),
                     ("ACK sense inverted", dict(mut=("ack_inv",))),
                     ("DLC > 8 not limited", dict(mut=("dlc_raw",))),
                     ("polynomial 0x4598", dict(crc_cfg=[("POLY", 0x4598)] + cp.CRC_CAN[1:])),
                     ("CRC init 0x7FFF", dict(crc_cfg=[cp.CRC_CAN[0], ("INIT", 0x7FFF)] + cp.CRC_CAN[2:])),
                     ("bit time 102 clocks instead of 100", dict(cpb=102))):
        cpb = kw.pop("cpb", B_CLK)
        tx_case(f"mutant TX: {name}", tx_frames, firmware=cp.can_tx(cpb, **kw), expect="fail")
    # ---- receiver
    f5 = cm.encode(0x234, [rnd.randrange(256) for _ in range(8)])
    items = [good(cm.random_frame(rnd, d)) for d in (0, 3, 8)] + [good(ff) for ff in (cm.encode(i, d) for i, d in find_frames(rnd))]
    items.append((corrupt_crc(f5, 3), rx_expect(f5, 2), False, 0))
