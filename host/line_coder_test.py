def mutation_check():
    global fast_fail
    src = open(os.path.join(ROOT, "src", "line_coder.v")).read()
    d = os.path.join(BUILD, "mut_src")
    caught = 0
    for old, new, desc in MUTANTS:
        if src.count(old) != 1:
            print(f"  MUTANT INVALID ({src.count(old)} matches): {desc}")
            continue
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
        open(os.path.join(d, "line_coder.v"), "w").write(src.replace(old, new))
        fast_fail = True
        try:
            run_all(build(d))
            print(f"  MUTANT MISSED   {desc}")
        except FailFast as e:
            caught += 1
            print(f"  mutant caught   {desc}   ({str(e)[:70]})")
        finally:
            fast_fail = False
    print(f"line coder mutants caught: {caught}/{len(MUTANTS)}")
    return caught == len(MUTANTS)


def main():
    if "mutants" in sys.argv[1:]:
        return 0 if mutation_check() else 1
    run_all(build())
    print(f"{checks} checks, {fails} failed")
    print(f"RESULT line_coder_test: {'PASS' if not fails else 'FAIL'} ({checks - fails}/{checks} checks)")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
